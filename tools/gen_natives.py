#!/usr/bin/env python3
"""Generates src/generated/Natives.g.h from tools/natives.txt and the native DB.

    python -I tools/gen_natives.py --db <folder with natives.json and natives_gen9.json>

The DB comes from github.com/alloc8or/gta5-nativedb-data and is only needed when
you add a native. It isn't shipped or checked in; the generated header is.

The generator refuses to emit a native unless it exists in BOTH files with the
same hash and the same parameter types, so a wrapper is valid on Legacy and on
Enhanced, or the build stops here instead of crashing a stream later.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST_FILE = ROOT / "tools" / "natives.txt"
OUT_FILE = ROOT / "src" / "generated" / "Natives.g.h"

# Reserved words and Windows macros that can't be used as parameter names.
BAD_PARAM_NAMES = {"default", "template", "new", "delete", "class", "this", "near", "far", "interface"}


def index(path):
    with open(path, encoding="utf-8") as f:
        db = json.load(f)
    return {e["name"]: (ns, h, e) for ns, entries in db.items() for h, e in entries.items()}


def param_list(entry):
    out = []
    for i, p in enumerate(entry.get("params", [])):
        name = p["name"] if p["name"] not in BAD_PARAM_NAMES else f'{p["name"]}_'
        out.append((p["type"], name or f"p{i}"))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", required=True, help="folder holding natives.json and natives_gen9.json")
    args = ap.parse_args()

    legacy = index(pathlib.Path(args.db) / "natives.json")
    gen9 = index(pathlib.Path(args.db) / "natives_gen9.json")

    names = [line.strip() for line in LIST_FILE.read_text(encoding="utf-8").splitlines()]
    names = [n for n in names if n and not n.startswith("#")]

    errors = []
    wrappers, hashes = [], []
    for name in names:
        a, b = legacy.get(name), gen9.get(name)
        if not a or not b:
            errors.append(f"{name}: missing from {'natives.json' if not a else 'natives_gen9.json'}")
            continue
        if a[1] != b[1]:
            errors.append(f"{name}: hash differs (legacy {a[1]}, gen9 {b[1]})")
            continue
        pa, pb = [t for t, _ in param_list(a[2])], [t for t, _ in param_list(b[2])]
        if pa != pb:
            errors.append(f"{name}: parameters differ (legacy {pa}, gen9 {pb})")
            continue
        if a[2].get("return_type") != b[2].get("return_type"):
            errors.append(f"{name}: return type differs")
            continue

        ns, hash_value, entry = b
        ret = entry.get("return_type", "void")
        params = param_list(entry)
        decl = ", ".join(f"{t} {n}" for t, n in params)
        call = "".join(f", {n}" for _, n in params)
        hashes.append(f"    inline constexpr uint64_t {name} = {hash_value};")
        wrappers.append(f"    inline {ret} {name}({decl}) {{ return Invoke<{ret}>(hash::{name}{call}); }} // {ns}")

    if errors:
        print("Native check failed:", file=sys.stderr)
        for e in errors:
            print("  " + e, file=sys.stderr)
        return 1

    body = "\n".join([
        "// GENERATED by tools/gen_natives.py from tools/natives.txt. Do not edit.",
        f"// {len(names)} natives, each checked against both natives.json and natives_gen9.json.",
        "#pragma once",
        "",
        "namespace cvs::nat",
        "{",
        "    namespace hash",
        "    {",
        "    " + "\n    ".join(hashes),
        "    }",
        "",
        *wrappers,
        "}",
        "",
    ])
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(body, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT_FILE} ({len(names)} natives)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
